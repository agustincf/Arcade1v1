export type PixelIconName = keyof typeof ICONS;

/**
 * `px`: tamaño de cada píxel en px de CSS (1 = el ícono mide lo que su bitmap;
 * en línea con texto de 11-16 px, 1 queda a la altura de las mayúsculas).
 * `label`: solo si el ícono va SOLO y dice algo (un botón sin texto); si
 * acompaña a un texto es decorativo y queda fuera del árbol de accesibilidad.
 */
export function PixelIcon({
  name,
  px = 1,
  className = "",
  label,
}: {
  name: PixelIconName;
  px?: number;
  className?: string;
  label?: string;
}) {
  const rows: Bitmap = ICONS[name];
  const { w, h } = bitmapSize(rows);
  // El alto viaja como variable para que .px-icon lo centre sobre las
  // mayúsculas del texto de al lado (globals.css).
  const style = { "--px-icon-h": `${h * px}px` } as CSSProperties;
  return (
    <svg
      width={w * px}
      height={h * px}
      viewBox={`0 0 ${w} ${h}`}
      shapeRendering="crispEdges"
      fill="currentColor"
      className={`px-icon ${className}`}
      style={style}
      {...(label ? { role: "img", "aria-label": label } : { "aria-hidden": true })}
    >
      {runs(rows).map((r, i) => (
        <rect key={i} x={r.x} y={r.y} width={r.w} height={1} />
      ))}
    </svg>
  );
}
